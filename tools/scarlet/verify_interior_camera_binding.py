"""Verify static Lua binding evidence from the Scarlet camera investigation.

Takes the JSON generated by trace_interior_camera_bindings.py. Read-only:
does not require the game, modify Lua data or claim live gameplay success.
"""
import argparse
import json
from pathlib import Path

from inspect_interior_camera import EXPECTED_SHA256

NAMESPACE = 'CD9AE7C27B00EB066'
MEMBER = 'SF667EA15F51B1676'
INTERPOLATOR = '0.30688'
CALLER = '0.17567'
ALSO_REFERENCES = '0.18722'


def verify(document):
    if document.get('file_sha256') != EXPECTED_SHA256:
        raise ValueError('Unexpected original Lua identity')
    roots = document['root_closure_registration_windows']
    matches = roots[INTERPOLATOR]
    if len(matches) != 1:
        raise ValueError('Interpolator root registration must be unique')
    c = matches[0]
    pc = c['closure_pc']
    ins = {i['pc']: i for i in c['instructions']}
    expected = {
        pc - 3: ('LOADK', NAMESPACE),
        pc - 2: ('GETTABLE', None),
        pc - 1: ('LOADK', MEMBER),
        pc: ('CLOSURE', None),
        pc + 1: ('SETTABLE', None),
    }
    for addr, (op, constant) in expected.items():
        row = ins.get(addr)
        if row is None or row['op'] != op:
            raise ValueError(f'Wrong register operation at root pc {addr}')
        if constant is not None and row.get('constant') != constant:
            raise ValueError(f'Wrong namespace/member at root pc {addr}')
    if ins[pc].get('child_path') != INTERPOLATOR:
        raise ValueError('Root closure does not register recorded interpolator')
    if not (ins[pc-3]['a'] == ins[pc-2]['b'] == ins[pc-2]['a']
            == ins[pc+1]['a']
            and ins[pc-1]['a'] == ins[pc+1]['b']
            and ins[pc]['a'] == ins[pc+1]['c']):
        raise ValueError('Root registration register dataflow differs')
    call = document['candidate_controller_call']
    if (call['proto'], call['namespace'], call['member']) != (CALLER, NAMESPACE, MEMBER):
        raise ValueError('Unexpected controller method lookup')
    if (call['pc_namespace'], call['pc_member'], call['pc_call']) != (31, 32, 37):
        raise ValueError('Controller call site changed')
    if call['four_arguments'] is not True:
        raise ValueError('Missing caller argument validation')
    refs = document['member_uses']
    other = [r for r in refs if r['proto'] == ALSO_REFERENCES
             and any(h.get('member') == MEMBER for h in r.get('hits', []))]
    if len(other) != 1:
        raise ValueError('Another known interpolator consumer was not found')
    return {
        'original_lua_sha256_verified': True,
        'static_registration_verified': f'{NAMESPACE}.{MEMBER} -> {INTERPOLATOR}',
        'static_lookup_in_controller_verified': CALLER,
        'another_member_consumer': ALSO_REFERENCES,
        'scope_risk': 'shared helper; patching this method globally affects other callers',
        'live_indoor_camera_path_validated': False,
        'active_gameplay_patch': False,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('binding_json', type=Path)
    args = parser.parse_args()
    print(json.dumps(verify(json.loads(args.binding_json.read_text(encoding='utf-8-sig'))),
                     indent=2))


if __name__ == '__main__':
    main()
